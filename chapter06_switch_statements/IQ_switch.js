let fruit = "apple";
switch (fruit) {
    case "banana":
        console.log("Banana")

    case "apple":
        console.log("Apple")

    case "orange":
        console.log("Orange")

    case "mango":
        console.log("Mango")

    case "strawberry":
        console.log("Strawberry")

    default:
        console.log("Invalid fruit")
}